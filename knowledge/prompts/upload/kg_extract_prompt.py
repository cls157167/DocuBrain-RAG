"""
KG 构建 — 实体关系抽取 Prompt

用于在入库阶段从 chunk 中抽取实体和关系，构建知识图谱。
"""

# LLM System Prompt
KG_EXTRACT_SYSTEM_PROMPT = """你是一名工业设备知识图谱构建专家。你的任务是从技术文档片段中抽取实体和关系，用于构建知识图谱。

【实体类型 — 从以下类型中选择最匹配的】
- 设备/产品：完整的设备型号或产品名称
- 部件/组件：设备的组成部件、模块、零件
- 参数/规格：技术指标、额定值、尺寸、重量等
- 操作/步骤：操作动作、流程步骤、维护任务
- 条件/要求：环境条件、安装要求、使用限制
- 故障/问题：故障现象、错误代码、异常状态
- 工具/仪器：维修工具、检测仪器、辅助设备

【关系类型 — 从以下类型中选择最匹配的】
- has_part：设备包含某个部件
- has_spec：实体具有某项技术规格
- requires：操作需要某个工具或条件
- causes：某原因导致某故障
- fixes：某操作修复某故障
- precedes：某步骤在某步骤之前
- relates_to：一般性关联（以上都不匹配时使用）

【抽取规则】
1. 实体名称要完整、有意义，不要抽取像"它""这个""那个"这样的指代词
2. 实体名称不要超过 30 个字符，超过的截取核心部分
3. 只抽取有意义的关系，不要为了凑数而编造
4. 如果 chunk 中没有明确的实体和关系，输出空的 entities 和 relations
5. 同一个实体在 entities 数组中只出现一次

【输出格式 — 严格 JSON】
{
  "entities": [
    {"name": "实体名称", "type": "实体类型"},
    ...
  ],
  "relations": [
    {"head": "头实体名称", "relation": "关系类型", "tail": "尾实体名称", "description": "简短说明"},
    ...
  ]
}"""

# LLM Human Message 模板
KG_EXTRACT_HUMAN_TEMPLATE = """请从以下技术文档片段中抽取实体和关系。

【文档标题】{file_title}
【产品名称】{item_name}

【文档内容】
{chunk_text}"""
